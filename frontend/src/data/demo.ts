const scale = (m: Money, f: number): Money => ({ ...m, amount: Math.round(m.amount * f) });

const levelFromScore = (score: number): RiskLevel =>
  score >= 80 ? "CRITICAL" : score >= 65 ? "HIGH" : score >= 40 ? "MODERATE" : "LOW";

/**
 * Returns the dossier for a counterparty. ABC Infrastructure is the fully
 * curated demo record; other counterparties reuse the same structure with
 * scaled figures so every screen stays populated.
 */
export function getDossier(companyId: string): CounterpartyDossier {
  const company = companies.find((c) => c.id === companyId) ?? companies[0]!;
  if (company.id === "E-ABC") return abcDossier;

  const f = (company.riskScore ?? 50) / 72;
  const shift = (score: number) => Math.max(8, Math.min(96, Math.round(score * f)));

  return {
    ...abcDossier,
    company,
    overallRisk: {
      ...overallRisk,
      score: company.riskScore ?? 50,
      level: company.riskLevel,
      previousScore: Math.max(5, (company.riskScore ?? 50) - 7),
    },
    risks: abcDossier.risks.map((r) => ({
      ...r,
      score: { ...r.score, score: shift(r.score.score), level: levelFromScore(shift(r.score.score)) },
      exposure: r.exposure ? scale(r.exposure, f) : undefined,
    })),
    exposure: {
      ...abcDossier.exposure,
      total: scale(abcDossier.exposure.total, f),
      funded: scale(abcDossier.exposure.funded, f),
      unfunded: scale(abcDossier.exposure.unfunded, f),
      potentialFutureExposure: scale(abcDossier.exposure.potentialFutureExposure, f),
      collateral: scale(abcDossier.exposure.collateral, f),
      net: scale(abcDossier.exposure.net, f),
    },
    exposureBreakdown: abcDossier.exposureBreakdown.map((e) => ({
      ...e,
      amount: Math.round(e.amount * f),
    })),
    graph: {
      centerId: "E-ABC",
      nodes: abcDossier.graph.nodes.map((n) =>
        n.id === "E-ABC" ? { ...n, label: company.name, riskLevel: company.riskLevel } : n,
      ),
      edges: abcDossier.graph.edges,
    },
  };
}

